/**
 * 用量展示的共享格式化（纯函数，**不引任何页面/组件/服务**）。
 *
 * ## 为什么单独抽出来
 *
 * 这两个函数原本只写在 `pages/Usage.tsx` 里（函数级 `nf` / `money`）。新增的趋势图与
 * 趋势图（`components/UsageTrend.tsx`）也要用同一套口径，就地各写一份
 * 必然漂移（表格显示 `12.3K`、图里却显示 `12345`）。放这里让两边 import 同一实现，
 * 顺带避免 `页面 → 组件 → 页面` 的循环依赖。
 *
 * ## 口径（与改造前逐字一致，未改语义）
 *
 * - `nf`：≥1000 显示为 `K`（≥10 万不保留小数，否则保留 1 位）；其余原样。
 * - `money`：`¥` 前缀；≥100 不保留小数，否则保留 2 位。
 */

/** token / 计数压缩：`1234 → 1.2K`、`150000 → 150K`。 */
export const nf = (n: number): string => (n >= 1000 ? `${(n / 1000).toFixed(n >= 100000 ? 0 : 1)}K` : String(n));

/** 费用展示：`¥12.50` / `¥120`。 */
export const money = (n: number): string => `¥${n.toFixed(n >= 100 ? 0 : 2)}`;
